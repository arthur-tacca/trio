from __future__ import annotations

import enum
from typing import TYPE_CHECKING, Generic, cast, overload

import attrs
import outcome

from .._util import final
from ._exceptions import Cancelled
from ._ki import enable_ki_protection
from ._run_context import GLOBAL_RUN_CONTEXT

if TYPE_CHECKING:
    from collections.abc import Callable, Generator

    from typing_extensions import TypeVar

    from ._task import CancelReason, Task

    # Both type parameters default to None: a bare ``WakeToken`` is a
    # ``WakeToken[None, None]``, and ``WakeToken[T]`` is ``WakeToken[T, None]``.
    T = TypeVar("T", default=None)
    D = TypeVar("D", default=None)
    # A method-scoped stand-in for T, for the constructor overload that pins
    # D to None (type checkers don't allow a class's own type parameters in
    # the self annotation of __init__).
    T1 = TypeVar("T1", default=None)
else:
    from typing import TypeVar

    # At runtime there are no defaults, so subscript with both parameters (or,
    # better, only in annotations).
    T = TypeVar("T")
    D = TypeVar("D")
    T1 = TypeVar("T1")


class _NoSend(enum.Enum):
    """Sentinel for :meth:`WakeToken.reschedule` being called without an
    outcome. Private, so callers can't pass it; the overloads say when it's
    allowed to be left out."""

    NO_SEND = enum.auto()


@final
@attrs.define(eq=False, repr=False, init=False)
class WakeToken(Generic[T, D]):
    """A single-use handle for putting the current task to sleep and waking
    it up again. This is Trio's native blocking primitive: every time a task
    blocks, it does so by awaiting one of these (usually indirectly, via some
    higher-level API).

    ``await token`` blocks the current task until some other code calls
    :meth:`reschedule` on the token, and then returns (or raises) whatever
    that call passed in. A token can be awaited exactly once, by exactly one
    task.

    Args:
      on_cancel: Called with the token as its only argument if a
          cancellation needs to be delivered while the token is being
          awaited. It should clean up whatever state refers to the token,
          and then either:

          * call :meth:`reschedule_cancelled` (now or later) to deliver the
            cancellation, or

          * do nothing, in which case the token must still be rescheduled by
            "someone" as normal, and the awaiting task can call
            :meth:`get_cancelled_exception` afterwards if it wants to raise
            the cancellation itself.

          It's a plain attribute, so it can be replaced while the token is
          outstanding. And if there's nothing to clean up,
          :meth:`reschedule_cancelled` itself will do::

              await WakeToken(WakeToken.reschedule_cancelled)
      data: Anything the code that puts the task to sleep wants to share
          with the code that wakes it up or cancels it. Trio never looks at
          it. It can only be left out when its type parameter is None, which
          is the default: ``WakeToken(on_cancel)`` is a ``WakeToken[T, None]``
          with ``data`` None, and ``WakeToken(on_cancel, lot)`` is a
          ``WakeToken[T, Lot]``.

    The :exc:`~trio.Cancelled` to deliver is created on demand by
    :meth:`get_cancelled_exception`, which can be called any number of times
    once ``on_cancel`` has been called. If ``on_cancel`` declines to
    deliver it, nothing is lost: the task is still cancelled, and will see
    that at its next checkpoint.

    Example, a minimal event::

        class Event:
            def __init__(self):
                self._flag = False
                self._waiting = set()

            def set(self):
                self._flag = True
                for token in self._waiting:
                    token.reschedule()
                self._waiting.clear()

            async def wait(self):
                if self._flag:
                    await trio.lowlevel.checkpoint()
                    return

                def on_cancel(token):
                    token.data._waiting.remove(token)
                    token.reschedule_cancelled()

                token = trio.lowlevel.WakeToken(on_cancel, self)
                self._waiting.add(token)
                await token

    """

    on_cancel: Callable[[WakeToken[T, D]], None]
    data: D
    # The task sleeping on us, bound by the run loop when the token is
    # yielded to it; None until then.
    _task: Task | None = attrs.field(init=False)
    # None until a cancellation is requested; then the reason it was
    # requested for, from which get_cancelled_exception() builds the
    # exception on demand.
    _cancel_reason: CancelReason | None = attrs.field(init=False)
    _rescheduled: bool = attrs.field(init=False)

    # The constructor is written out rather than generated by attrs so that
    # it can be overloaded: ``data`` may only be left out when D is None.
    @overload
    def __init__(
        self: WakeToken[T1, None],
        on_cancel: Callable[[WakeToken[T1, None]], None],
    ) -> None: ...
    @overload
    def __init__(
        self,
        on_cancel: Callable[[WakeToken[T, D]], None],
        data: D,
    ) -> None: ...
    def __init__(  # type: ignore[misc]  # mypy doesn't follow the self type of the first overload
        self,
        on_cancel: Callable[[WakeToken[T, D]], None],
        data: D | None = None,
    ) -> None:
        self.on_cancel = on_cancel
        # Only ever None when D is None, per the overloads above.
        self.data = cast("D", data)
        self._task = None
        self._cancel_reason = None
        self._rescheduled = False

    @property
    def task(self) -> Task:
        """The task awaiting this token.

        For debugging and introspection. It's set when the token is awaited,
        and stays set after the token has been rescheduled, so a waker can
        still see who it woke.

        Raises:
          RuntimeError: if the token hasn't been awaited yet.
        """
        if self._task is None:
            raise RuntimeError("this WakeToken hasn't been awaited yet")
        return self._task

    def __repr__(self) -> str:
        if self._task is None:
            state = "not awaited"
        elif self._rescheduled:
            state = f"rescheduled, was awaited by {self._task.name!r}"
        else:
            state = f"awaited by {self._task.name!r}"
        if self._cancel_reason is not None:
            state += ", cancellation requested"
        return f"<WakeToken at {id(self):#x}: {state}>"

    # __await__ must return an iterator (Python rejects an ``async def``
    # here with "__await__() returned a coroutine"), so this is a generator:
    # it yields the token itself to the run loop, and unwraps the outcome
    # that the loop sends back in once the token has been rescheduled. (The
    # outcome is deliberately not bound to a name, so that this frame doesn't
    # keep it alive when it raises.)
    @enable_ki_protection
    def __await__(self) -> Generator[WakeToken[T, D], outcome.Outcome[T], T]:
        if self._task is not None:
            raise RuntimeError("a WakeToken can only be awaited once")
        return (yield self).unwrap()

    # Called by the run loop, at most once per token, when a cancellation
    # needs delivering to the sleeping task.
    def _request_cancel(self, reason: CancelReason) -> None:
        assert self._cancel_reason is None
        self._cancel_reason = reason
        self.on_cancel(self)

    @property
    def _cancel_requested(self) -> bool:
        return self._cancel_reason is not None

    # The outcome may only be left out when None is a valid value for the
    # token, i.e. its value type is None or a union including it.
    @overload
    def reschedule(self: WakeToken[T | None, D]) -> None: ...
    @overload
    def reschedule(self, next_send: outcome.Outcome[T]) -> None: ...
    @enable_ki_protection
    def reschedule(
        self,
        next_send: outcome.Outcome[T] | _NoSend = _NoSend.NO_SEND,
    ) -> None:
        """Wake the task awaiting this token, making ``await token`` return
        (or raise) ``next_send``.

        ``next_send`` can be left out if the token's value type is (or
        includes) None, in which case the task is woken with
        ``outcome.Value(None)``.

        Must be called exactly once, after the token has been awaited.
        """
        to_send: outcome.Outcome[object]
        if next_send is _NoSend.NO_SEND:
            to_send = outcome.Value(None)
        elif isinstance(next_send, outcome.Outcome):
            to_send = next_send
        else:
            raise TypeError(
                f"WakeToken.reschedule() needs an outcome.Outcome, not {next_send!r}",
            )
        if self._task is None:
            raise RuntimeError(
                "WakeToken.reschedule() called before the token was awaited",
            )
        if self._rescheduled:
            raise RuntimeError("WakeToken.reschedule() called more than once")
        self._rescheduled = True
        GLOBAL_RUN_CONTEXT.runner._enqueue(self._task, to_send)

    def get_cancelled_exception(self) -> Cancelled:
        """Create the :exc:`~trio.Cancelled` for the pending cancellation, to
        raise or to pass to :meth:`reschedule` (:meth:`reschedule_cancelled`
        does both).

        Can only be called after ``on_cancel`` has been called. Each call
        returns a new, equivalent exception, so calling it more than once
        is fine.
        """
        reason = self._cancel_reason
        if reason is None:
            raise RuntimeError(
                "WakeToken.get_cancelled_exception() called before any "
                "cancellation was requested",
            )
        return Cancelled._create(
            source=reason.source,
            reason=reason.reason,
            source_task=reason.source_task,
        )

    @enable_ki_protection
    def reschedule_cancelled(self) -> None:
        """Wake the awaiting task with the cancellation that ``on_cancel``
        was asked to deliver. Convenience for the common case."""
        self.reschedule(outcome.Error(self.get_cancelled_exception()))
